// Builds public/sw.js (#81) from two sources:
//   features/pwa/sw/strategy.ts – routing rules (pure, unit-tested), compiled with the
//                        TypeScript compiler the project already has
//   features/pwa/sw/worker.js   – the worker itself (events and caching strategies)
// and stamps a per-build version into it, so every deploy gets fresh caches
// and the browser sees a changed worker. Runs automatically before
// `npm run build` (prebuild); the output is generated and git-ignored.
import { readFile, writeFile } from "node:fs/promises";
import { execSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Script } from "node:vm";
import ts from "typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Render sets RENDER_GIT_COMMIT; locally git is asked. The build time is
 * added so a redeploy of the same commit also counts as a new version. */
function buildVersion() {
  let commit = process.env.RENDER_GIT_COMMIT;
  if (!commit) {
    try {
      commit = execSync("git rev-parse HEAD", { cwd: root, stdio: ["ignore", "pipe", "ignore"] })
        .toString()
        .trim();
    } catch {
      commit = "";
    }
  }
  const stamp = Date.now().toString(36);
  return commit ? `${commit.slice(0, 7)}-${stamp}` : stamp;
}

const strategySource = await readFile(join(root, "features/pwa/sw/strategy.ts"), "utf8");
const strategy = ts
  .transpileModule(strategySource, {
    compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext },
  })
  .outputText.replace(/^export \{\};?\s*$/gm, "")
  .replace(/^export /gm, "");
if (/^\s*(import|export)\b/m.test(strategy)) {
  throw new Error(
    "features/pwa/sw/strategy.ts must not import anything (it is inlined into the worker).",
  );
}

const version = buildVersion();
const worker = (await readFile(join(root, "features/pwa/sw/worker.js"), "utf8")).replace(
  "__SW_VERSION__",
  version,
);

const output = `// Generated by scripts/build-sw.mjs from features/pwa/sw/strategy.ts and features/pwa/sw/worker.js — do not edit.
"use strict";
${strategy}
${worker}`;
new Script(output, { filename: "sw.js" }); // throws on a syntax error
await writeFile(join(root, "public/sw.js"), output);
console.log(`public/sw.js written (version ${version}).`);
